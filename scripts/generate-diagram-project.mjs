import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const app = resolve(root, "app-v2");
const [basePath, interpretationPath, outputPath] = process.argv.slice(2);
if (!basePath || !interpretationPath || !outputPath) throw new Error("用法：node scripts/generate-diagram-project.mjs 基础项目.blockout.json 解释.json 新候选.blockout.json");
if ([resolve(basePath), resolve(interpretationPath)].includes(resolve(outputPath))) throw new Error("候选输出不能覆盖输入文件");
execFileSync(process.execPath, [resolve(app, "node_modules/typescript/bin/tsc"), "-p", "tsconfig.domain-cjs.json"], { cwd: app, stdio: "inherit" });
await writeFile(resolve(app, ".domain-verify/package.json"), '{"type":"commonjs"}\n', "utf8");
const require = createRequire(import.meta.url);
const { projectSchema } = require(resolve(app, ".domain-verify/project-schema.js"));
const { interpretDiagram } = require(resolve(app, ".domain-verify/diagram-import.js"));
const { validateProject } = require(resolve(app, ".domain-verify/validation.js"));
const { resolveAssembly } = require(resolve(app, ".domain-verify/assembly-resolver.js"));
const project = projectSchema.parse(JSON.parse(await readFile(resolve(basePath), "utf8")));
const input = JSON.parse(await readFile(resolve(interpretationPath), "utf8"));
const module = project.modules.find((item) => item.id === input.moduleId);
if (!module?.reference) throw new Error("请先在网页给目标模块配置并校准底图，保存/导出基础项目");
const result = interpretDiagram(input, module, module.reference, project.blockoutProfile);
result.module.revision += 1;
project.modules = project.modules.map((item) => item.id === module.id ? result.module : item);
project.updatedAt = new Date().toISOString();
projectSchema.parse(project);
await writeFile(resolve(outputPath), `${JSON.stringify(project, null, 2)}\n`, { encoding: "utf8", flag: "wx" });
console.log(JSON.stringify({ output: resolve(outputPath), added: result.added, changed: result.changed, removed: result.removed, retained: result.retained, validation: validateProject(project), assembly: resolveAssembly(project).issues }, null, 2));
